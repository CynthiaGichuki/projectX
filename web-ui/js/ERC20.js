let selectedWallet = null;

// Show the popup to select wallet
function showWalletPopup() {
    const popup = document.getElementById('wallet-popup');
    popup.style.display = 'block';

    // Populate the wallet selection
    const walletSelect = document.getElementById('wallet-select');
    walletSelect.innerHTML = '';
    const wallets = getAddresses();
    wallets.forEach(wallet => {
        const option = document.createElement('option');
        option.value = wallet.address;
        option.textContent = wallet.address;
        walletSelect.appendChild(option);
    });
}

// Hide the popup
function hideWalletPopup() {
    const popup = document.getElementById('wallet-popup');
    popup.style.display = 'none';
}

// Get the selected wallet
function getSelectedWallet() {
    const walletSelect = document.getElementById('wallet-select');
    selectedWallet = walletSelect.value;
    hideWalletPopup();
}

// Update the balance display
async function updateBalance() {
    const balanceElement = document.getElementById('balance');
    const balance = await callContractMethod(contractAddress, abi, 'balanceOf', [selectedWallet]);
    console.log("Balance:", balance);
    const decimals = await callContractMethod(contractAddress, abi, 'decimals', []);
    // Use BigNumber to handle large integer arithmetic
    const adjustedBalance = ethers.BigNumber.from(balance).div(ethers.BigNumber.from(10).pow(decimals));
    balanceElement.textContent = ethers.utils.formatUnits(balance, decimals);
}

// Perform the transaction
async function performTransaction(method, params) {
    if (!selectedWallet) {
        showWalletPopup();
        document.getElementById('select-wallet').onclick = async () => {
            getSelectedWallet();
            await performTransaction(method, params);
        };
        return;
    }

    try {
        await sendTransaction(contractAddress, abi, method, params, selectedWallet);
        await updateBalance();
    } catch (error) {
        console.error(`Error performing ${method}:`, error);
    }
}

// Perform the transaction
async function changeAddress() {
    showWalletPopup();
    document.getElementById('select-wallet').onclick = async () => {
        getSelectedWallet();
        await updateBalance();
    };
    return;
}

document.getElementById('transfer').onclick = () => {
    const recipient = document.getElementById('recipient').value;
    const amount = document.getElementById('amount').value;
    performTransaction('transfer', [recipient, amount]);
};
document.getElementById('approve').onclick = () => {
    const spender = document.getElementById('recipient').value;
    const amount = document.getElementById('amount').value;
    performTransaction('approve', [spender, amount]);
};
document.getElementById('balanceOf').onclick = updateBalance;
document.getElementById('change_address').onclick = () => changeAddress();

window.onload = async () => {
    await updateBalance();
};
